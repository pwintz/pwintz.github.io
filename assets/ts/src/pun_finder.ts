// Wiktionary definitions are HTML; only their text is kept, so no markup reaches the page.
function htmlToText(html: string): string {
  return (new DOMParser().parseFromString(html, "text/html").body.textContent ?? "").replace(/\s+/g, " ").trim();
}

async function fetchSenses(title: string): Promise<Sense[] | null> {
  const response = await fetch(DEFINITION_API + encodeURIComponent(title), {
    headers: { "Api-User-Agent": "Pun Finder (https://paulwintz.com/tools/pun_finder/)" },
  });
  if (response.status === 404) {
    return null;
  }
  if (!response.ok) {
    throw new Error(`HTTP ${response.status}`);
  }
  const json = await response.json() as { en?: { partOfSpeech: string; definitions: { definition: string }[] }[] };
  const senses = (json.en ?? []).map((entry) => ({
    partOfSpeech: entry.partOfSpeech,
    definitions : entry.definitions.map((d) => htmlToText(d.definition)).filter(Boolean),
  })).filter((sense) => sense.definitions.length > 0);
  return senses.length > 0 ? senses : null;
}

// Tries the word as displayed ("Caitlin"), then with the other capitalization, since Wiktionary
// titles are case-sensitive. Resolves to null if neither has English definitions.
function definitionsOf(word: string): Promise<{ title: string; senses: Sense[] } | null> {
  let cached = definitionCache.get(word);
  if (!cached) {
    const lower  = word.toLowerCase();
    const titles = [word, word === lower ? word[0].toUpperCase() + word.slice(1) : lower];
    cached = (async () => {
      for (const title of titles) {
        const senses = await fetchSenses(title);
        if (senses) {
          return { title, senses };
        }
      }
      return null;
    })();
    // Don't cache failures (e.g. no connection), so that trying again can work.
    cached.catch(() => definitionCache.delete(word));
    definitionCache.set(word, cached);
  }
  return cached;
}

function renderGuide(container: HTMLElement): void {
  for (const [heading, sounds] of [["Vowels", GUIDE_VOWELS], ["Consonants", GUIDE_CONSONANTS]] as const) {
    const title = document.createElement("h3");
    title.textContent = heading;
    const grid = document.createElement("dl");
    grid.className = "pf-guide-grid";
    for (const [phone, example] of sounds) {
      const item   = document.createElement("div");
      const symbol = document.createElement("dt");
      // Show the vowels without stress accents, since the accent is explained separately.
      symbol.textContent = ipaOf(phone.replace(/[12]$/, ""));
      const word = document.createElement("dd");
      word.textContent = example ?? PHONEMES[baseOf(phone)].example;
      item.append(symbol, word);
      grid.append(item);
    }
    container.append(title, grid);
  }
}

function describePhone(phone: string): string {
  const info   = PHONEMES[baseOf(phone)];
  const digit  = phone.match(/\d/)?.[0];
  const stress = digit ? `, ${STRESS_NAMES[Number(digit)]}` : "";
  return info ? `/${ipaOf(phone)}/ as in "${info.example}"${stress}` : phone;
}

// The selection as URL text: positions separated by ",", each optionally followed by ":" and its
// sounds joined with ".". A bare position means just the original sound. E.g. "0,1:EH.AE,2".
function encodeSelection(selection: Selection, phones: string[]): string {
  return [...selection.keys()].sort((a, b) => a - b).map((i) => {
    const sounds = [...selection.get(i)!];
    return sounds.length === 1 && sounds[0] === baseOf(phones[i]) ? String(i) : `${i}:${sounds.join(".")}`;
  }).join(",");
}

function decodeSelection(text: string, phones: string[]): Selection {
  const selection: Selection = new Map();
  for (const part of text.split(",").filter(Boolean)) {
    const [index, sounds] = part.split(":");
    const i = Number(index);
    if (!Number.isInteger(i) || i < 0 || i >= phones.length) {
      continue;
    }
    const valid = (sounds ? sounds.split(".") : [baseOf(phones[i])]).filter((sound) => sound in PHONEMES);
    if (valid.length > 0) {
      selection.set(i, new Set(valid));
    }
  }
  return selection;
}

function initPage(): void {
  const $ = <T extends HTMLElement>(id: string): T => document.getElementById(id) as T;
  const form         = $<HTMLFormElement>("pf-form");
  const input        = $<HTMLInputElement>("pf-input");
  const status       = $<HTMLParagraphElement>("pf-status");
  const pronList     = $<HTMLDivElement>("pf-pronunciations");
  const optionsBox   = $<HTMLFieldSetElement>("pf-options");
  const lettersOnly  = $<HTMLInputElement>("pf-letters-only");
  const commonness   = $<HTMLSelectElement>("pf-commonness");
  const hideOffensive = $<HTMLInputElement>("pf-hide-offensive");
  const summary      = $<HTMLParagraphElement>("pf-summary");
  const results      = $<HTMLDivElement>("pf-results");
  const moreButton   = $<HTMLButtonElement>("pf-more");
  const guideToggle  = $<HTMLButtonElement>("pf-guide-toggle");
  const guide        = $<HTMLDivElement>("pf-guide");
  const popover      = $<HTMLDivElement>("pf-definition");
  let popoverButton: HTMLButtonElement | null = null;  // The "?" button whose definition is shown

  let dict: Dictionary | null = null;
  let wordInfo = new Map<string, WordInfo>();  // Empty if the word data fails to load
  let pronunciations: string[][] = [];
  let activePron = 0;                      // Which pronunciation the selection belongs to
  let selection: Selection = new Map();    // Selected sounds in that pronunciation
  let stressLocked = new Set<number>();    // Positions in it whose stress must match
  let anchorStart = false;                 // Matches must start at the start of the word
  let anchorEnd   = false;                 // Matches must end at the end of the word
  let matches: Match[] = [];
  let groupSizes = new Map<number, number>();  // Group number → matches in it
  let shown = 0;
  let shownGroup = -1;                     // Group of the last match shown
  let groupList: HTMLUListElement | null = null;  // List the next match in that group goes in

  function setStatus(message: string, isError = false): void {
    status.textContent = message;
    status.hidden = !message;
    status.classList.toggle("pf-error", isError);
  }

  function readOptions(): SearchOptions {
    const words = commonness.value as WordFilter;
    return {
      anchorStart, anchorEnd, stressLocked,
      lettersOnly: lettersOnly.checked, words, hideOffensive: hideOffensive.checked,
    };
  }

  // Keeps the word and selection in the URL, so a search can be bookmarked or shared.
  function updateUrl(): void {
    const params = new URLSearchParams();
    if (input.value.trim()) {
      params.set("word", input.value.trim());
    }
    if (selection.size > 0) {
      if (activePron > 0) {
        params.set("pron", String(activePron));
      }
      params.set("sel", encodeSelection(selection, pronunciations[activePron]));
      if (stressLocked.size > 0) {
        params.set("stress", [...stressLocked].sort((a, b) => a - b).join(","));
      }
    }
    if (anchorStart || anchorEnd) {
      params.set("at", anchorStart && anchorEnd ? "whole" : anchorStart ? "start" : "end");
    }
    const query = params.toString().replace(/%2C/g, ",").replace(/%3A/g, ":");
    history.replaceState(null, "", location.pathname + (query ? "?" + query : ""));
  }

  // ⋘──────── Pronunciations ────────⋙

  // A button for one sound at one position: the original (large) or an alternative (small).
  function soundButton(p: number, i: number, sound: string, stress: string, reason?: string): HTMLButtonElement {
    const button = document.createElement("button");
    button.type = "button";
    button.className = reason ? "pf-chip pf-alt" : "pf-chip";
    const isOn = p === activePron && (selection.get(i)?.has(sound) ?? false);
    button.classList.toggle("pf-on", isOn);
    button.setAttribute("aria-pressed", String(isOn));
    const phone = withStress(sound, stress);
    button.title = describePhone(phone) + (reason ? ` (${reason})` : "");
    // Alternatives are labeled with how they differ; originals show only the IPA symbol.
    button.innerHTML = reason
      ? `<span class="pf-chip-ipa"></span><span class="pf-chip-reason"></span>`
      : `<span class="pf-chip-ipa"></span>`;
    // Stress is shown and locked by the separate toggle in the corner (see stressToggle).
    button.querySelector(".pf-chip-ipa")!.textContent = ipaOf(phone);
    if (reason) {
      button.querySelector(".pf-chip-reason")!.textContent = reason;
    }
    button.addEventListener("click", () => toggle(p, i, sound));
    return button;
  }

  // The stress mark in the corner of a stressed vowel's button. Clicking it locks the stress:
  // matching words must stress that vowel the same way.
  function stressToggle(p: number, i: number, phone: string): HTMLButtonElement {
    const mark   = stressMarkOf(phone);
    const kind   = mark === "ˈ" ? "main" : "secondary";
    const locked = p === activePron && stressLocked.has(i);
    const button = document.createElement("button");
    button.type = "button";
    button.className = `pf-stress pf-stress-${kind}`;
    button.classList.toggle("pf-on", locked);
    const glyph = document.createElement("span");
    glyph.textContent = mark;
    button.append(glyph);
    button.setAttribute("aria-pressed", String(locked));
    button.setAttribute("aria-label", `Require ${kind} stress on /${ipaOf(phone)}/`);
    button.title = locked
      ? `Only words with ${kind} stress on this vowel. Click to allow any stress.`
      : `This vowel has ${kind} stress. Click to only match words that stress it the same way.`;
    button.addEventListener("click", () => toggleStress(p, i));
    return button;
  }

  // A toggle beside the first or last selected sound that pins the match to the start or end of
  // the word. Off, it shows "…" (other sounds can come before or after); on, a bracket.
  function anchorToggle(side: "start" | "end"): HTMLButtonElement {
    const on = side === "start" ? anchorStart : anchorEnd;
    const where = side === "start" ? "start" : "end";
    const button = document.createElement("button");
    button.type = "button";
    button.className = `pf-anchor pf-anchor-${side}`;
    button.classList.toggle("pf-on", on);
    button.textContent = on ? (side === "start" ? "⟦" : "⟧") : "…";
    button.setAttribute("aria-pressed", String(on));
    button.setAttribute("aria-label", `Match at the ${where} of the word`);
    button.title = on
      ? `Only words that ${side === "start" ? "start" : "end"} with these sounds. Click to allow other sounds ${side === "start" ? "before" : "after"} them.`
      : `Words can have other sounds ${side === "start" ? "before" : "after"} these. Click to only match words that ${side === "start" ? "start" : "end"} with them.`;
    button.addEventListener("click", () => {
      if (side === "start") {
        anchorStart = !anchorStart;
      } else {
        anchorEnd = !anchorEnd;
      }
      renderPronunciations();
      search();
      updateUrl();
      pronList.querySelector<HTMLButtonElement>(`.pf-anchor-${side}`)?.focus();
    });
    return button;
  }

  function renderPronunciations(): void {
    pronList.replaceChildren();
    pronunciations.forEach((phones, p) => {
      const row = document.createElement("div");
      row.className = "pf-pron";
      const label = document.createElement("span");
      label.className = "pf-pron-ipa";
      label.textContent = "/" + ipaPronunciation(phones) + "/";
      row.append(label);

      // One column per sound: the sound itself, then its alternatives.
      const slots = document.createElement("div");
      slots.className = "pf-slots";
      const selected = p === activePron ? [...selection.keys()] : [];
      const first = Math.min(...selected);
      const last  = Math.max(...selected);
      phones.forEach((phone, i) => {
        if (i === first) {
          slots.append(anchorToggle("start"));
        }
        const slot   = document.createElement("div");
        slot.className = "pf-slot";
        const stress = phone.match(/\d/)?.[0] ?? "";
        slot.append(soundButton(p, i, baseOf(phone), stress));
        if (stressMarkOf(phone)) {
          slot.append(stressToggle(p, i, phone));
        }
        for (const alternative of alternativesOf(baseOf(phone))) {
          slot.append(soundButton(p, i, alternative.phone, stress, alternative.reason));
        }
        slots.append(slot);
        if (i === last) {
          slots.append(anchorToggle("end"));
        }
      });
      row.append(slots);
      pronList.append(row);
    });
    optionsBox.hidden = pronunciations.length === 0;
  }

  // Selecting in a different pronunciation starts a new selection there.
  function switchPronunciation(p: number): void {
    if (p !== activePron) {
      activePron = p;
      selection = new Map();
      stressLocked = new Set();
    }
  }

  // Locking a vowel's stress also selects it, if it isn't already.
  function toggleStress(p: number, i: number): void {
    switchPronunciation(p);
    if (stressLocked.has(i)) {
      stressLocked.delete(i);
    } else {
      stressLocked.add(i);
      if (!selection.has(i)) {
        selection.set(i, new Set([baseOf(pronunciations[p][i])]));
      }
    }
    renderPronunciations();
    search();
    updateUrl();
  }

  function toggle(p: number, i: number, sound: string): void {
    switchPronunciation(p);
    const sounds = selection.get(i) ?? new Set<string>();
    if (sounds.has(sound)) {
      sounds.delete(sound);
    } else {
      sounds.add(sound);
    }
    if (sounds.size > 0) {
      selection.set(i, sounds);
    } else {
      selection.delete(i);
      stressLocked.delete(i);
    }
    renderPronunciations();
    search();
    updateUrl();
  }

  function lookUp(initial?: { pron: number; sel: string; stress: string }): void {
    if (!dict) {
      return;
    }
    const text = input.value.trim();
    const { pronunciations: found, missing } = pronunciationsOf(text, dict);
    pronunciations = found;
    activePron = 0;
    selection = new Map();
    stressLocked = new Set();
    if (initial && initial.pron >= 0 && initial.pron < found.length) {
      activePron = initial.pron;
      selection  = decodeSelection(initial.sel, found[initial.pron]);
      stressLocked = new Set(initial.stress.split(",").filter(Boolean).map(Number)
        .filter((i) => selection.has(i) && stressMarkOf(found[initial.pron][i])));
    }
    // A new word starts with all of its sounds selected.
    if (selection.size === 0 && found.length > 0) {
      selection = new Map(found[activePron].map((phone, i) => [i, new Set([baseOf(phone)])]));
    }
    if (!text) {
      setStatus("");
    } else if (missing.length > 0) {
      setStatus(`Not in the dictionary: ${missing.join(", ")}. Try a different spelling.`, true);
    } else {
      setStatus((found.length === 1 ? "" : `Found ${found.length} pronunciations; the first is selected. `)
        + "Click sounds to deselect the ones you don't want to pun on.");
    }
    renderPronunciations();
    search();
    updateUrl();
  }

  // ⋘──────── Results ────────⋙

  function search(): void {
    closeDefinition();
    results.replaceChildren();
    shown = 0;
    shownGroup = -1;
    groupList = null;
    if (!dict || selection.size === 0) {
      matches = [];
      summary.hidden = true;
      moreButton.hidden = true;
      return;
    }
    const exclude = new Set(input.value.trim().toLowerCase().split(/\s+/));
    const phones  = pronunciations[activePron];
    matches = findMatches(phones, selection, exclude, dict, wordInfo, readOptions());
    groupSizes = new Map();
    for (const match of matches) {
      groupSizes.set(groupOf(match), (groupSizes.get(groupOf(match)) ?? 0) + 1);
    }
    // E.g. /ˈl(ɛ|æ)t…s/: alternatives in parentheses, gaps as "…". Stress marks are placed
    // within each run of selected sounds, using the original sounds.
    const soundText = (i: number): string => {
      const stress = phones[i].match(/\d/)?.[0] ?? "";
      const ipas = [...selection.get(i)!].map((sound) => ipaOf(withStress(sound, stress)));
      return ipas.length === 1 ? ipas[0] : `(${ipas.join("|")})`;
    };
    const sound = runsOf([...selection.keys()].sort((a, b) => a - b))
      .map((run) => {
        const marks = stressMarkPositions(run.map((i) => phones[i]));
        return run.map((i, k) => (marks.get(k) ?? "") + soundText(i)).join("");
      })
      .join("…");
    const one  = matches.length === 1;
    const verb = anchorStart && anchorEnd ? (one ? "sounds like" : "sound like")
      : anchorStart ? (one ? "starts with" : "start with")
      : anchorEnd   ? (one ? "ends with" : "end with")
      : (one ? "contains" : "contain");
    summary.textContent = `${matches.length.toLocaleString()} ${one ? "word" : "words"} ${verb} /${sound}/.`;
    summary.hidden = false;
    showMore();
  }

  function showMore(): void {
    const next = matches.slice(shown, shown + PAGE_SIZE);
    for (const match of next) {
      // Each group gets a heading and its own list; "Show more" can continue a group.
      const group = groupOf(match);
      if (group !== shownGroup || !groupList) {
        const heading = document.createElement("h3");
        heading.className = "pf-group";
        heading.textContent = groupLabel(group);
        const count = document.createElement("span");
        count.className = "pf-group-count";
        count.textContent = (groupSizes.get(group) ?? 0).toLocaleString();
        heading.append(" ", count);
        groupList = document.createElement("ul");
        groupList.className = "pf-results";
        results.append(heading, groupList);
        shownGroup = group;
      }

      const info = wordInfo.get(match.word);
      const display = info?.display ?? match.word;
      const item = document.createElement("li");
      item.className = "pf-result";
      const word = document.createElement("span");
      word.className = "pf-result-word";
      word.textContent = display;
      if (wordInfo.size > 0) {
        // Frequency rank, e.g. "#56,367": the word's place among all words in the dictionary,
        // from most to least common.
        const rank = document.createElement("span");
        rank.className = "pf-rank";
        rank.textContent = match.rank === Infinity ? "unranked" : `#${match.rank.toLocaleString()}`;
        rank.title = match.rank === Infinity
          ? "Too rare to have a frequency ranking"
          : `Frequency rank ${match.rank.toLocaleString()} of ${wordInfo.size.toLocaleString()} (1 is the most common word)`;
        word.append(" ", rank);
        if (!info?.kind) {
          item.classList.add("pf-rare");
          item.title = "Not in the spelling dictionary; probably a rare name or spelling";
        }
      }
      const phones = document.createElement("span");
      phones.className = "pf-result-phones";
      const marks = stressMarkPositions(match.phones);
      match.phones.forEach((phone, i) => {
        // Stress marks go outside the highlights, which are for sounds.
        if (marks.has(i)) {
          phones.append(marks.get(i)!);
        }
        const isOriginal = match.highlighted.get(i);
        const part = document.createElement(isOriginal === undefined ? "span" : "mark");
        if (isOriginal === false) {
          part.className = "pf-substituted";
        }
        part.textContent = ipaOf(phone);
        part.title = describePhone(phone) + (isOriginal === false ? " (similar sound)" : "");
        phones.append(part);
      });
      const define = document.createElement("button");
      define.type = "button";
      define.className = "pf-define";
      define.innerHTML = QUESTION_ICON;
      define.setAttribute("aria-label", `Define ${display}`);
      define.setAttribute("aria-expanded", "false");
      define.setAttribute("aria-controls", "pf-definition");
      define.title = "Definition";
      define.addEventListener("click", () => {
        if (popoverButton === define) {
          closeDefinition();
        } else {
          showDefinition(define, display);
        }
      });
      item.append(word, phones, define);
      if (info?.offensive) {
        const warning = document.createElement("span");
        warning.className = "pf-offensive";
        warning.textContent = `⚠ ${OFFENSIVE_LABELS[info.offensive]}`;
        item.append(warning);
      }
      groupList.append(item);
    }
    shown += next.length;
    moreButton.hidden = shown >= matches.length;
    moreButton.textContent = `Show more (${(matches.length - shown).toLocaleString()} left)`;
  }

  // ⋘──────── Definition popover ────────⋙

  // Places the popover below the button, kept within the tool's width.
  function positionPopover(): void {
    if (!popoverButton) {
      return;
    }
    const container = popover.offsetParent?.getBoundingClientRect() ?? new DOMRect();
    const button    = popoverButton.getBoundingClientRect();
    const maxLeft   = container.width - popover.offsetWidth;
    popover.style.left = `${Math.max(0, Math.min(button.right - container.left - popover.offsetWidth, maxLeft))}px`;
    popover.style.top  = `${button.bottom - container.top + 6}px`;
  }

  function showDefinition(button: HTMLButtonElement, word: string): void {
    popoverButton?.setAttribute("aria-expanded", "false");
    popoverButton = button;
    button.setAttribute("aria-expanded", "true");
    const heading = document.createElement("strong");
    heading.textContent = word;
    const loading = document.createElement("p");
    loading.textContent = "Looking up the definition…";
    popover.replaceChildren(heading, loading);
    popover.hidden = false;
    positionPopover();

    definitionsOf(word).then((result) => {
      if (popoverButton !== button) {
        return;  // Another word was opened while this one loaded.
      }
      const content: Node[] = [heading];
      if (!result) {
        const none = document.createElement("p");
        none.textContent = "No definition found on Wiktionary.";
        content.push(none);
      } else {
        for (const sense of result.senses.slice(0, MAX_SENSES)) {
          const pos = document.createElement("p");
          pos.className = "pf-definition-pos";
          pos.textContent = sense.partOfSpeech;
          const list = document.createElement("ol");
          for (const definition of sense.definitions.slice(0, MAX_DEFINITIONS)) {
            const item = document.createElement("li");
            item.textContent = definition;
            list.append(item);
          }
          content.push(pos, list);
        }
        const link = document.createElement("a");
        link.href = WIKTIONARY_PAGE + encodeURIComponent(result.title) + "#English";
        link.target = "_blank";
        link.rel = "noopener";
        link.textContent = "More on Wiktionary";
        content.push(link);
      }
      popover.replaceChildren(...content);
      positionPopover();
    }).catch((error) => {
      if (popoverButton === button) {
        loading.textContent = `Couldn't load the definition (${error.message}).`;
        loading.classList.add("pf-error");
      }
    });
  }

  function closeDefinition(): void {
    popoverButton?.setAttribute("aria-expanded", "false");
    popoverButton = null;
    popover.hidden = true;
  }

  // Close on Escape or a click outside the popover (clicks on "?" buttons are handled above).
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && popoverButton) {
      const button = popoverButton;
      closeDefinition();
      button.focus();
    }
  });
  document.addEventListener("click", (event) => {
    const target = event.target as Element;
    if (popoverButton && !popover.contains(target) && !target.closest(".pf-define")) {
      closeDefinition();
    }
  });
  window.addEventListener("resize", positionPopover);

  // ⋘──────── Events and startup ────────⋙

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    lookUp();
  });
  optionsBox.addEventListener("change", () => {
    search();
  });
  moreButton.addEventListener("click", showMore);

  renderGuide($<HTMLDivElement>("pf-guide-sounds"));
  guideToggle.addEventListener("click", () => {
    guide.hidden = !guide.hidden;
    guideToggle.setAttribute("aria-expanded", String(!guide.hidden));
  });

  const params = new URLSearchParams(location.search);
  input.value = params.get("word") ?? "";
  const initial = { pron: Number(params.get("pron") ?? 0), sel: params.get("sel") ?? "", stress: params.get("stress") ?? "" };
  const at = params.get("at");
  anchorStart = at === "start" || at === "whole";
  anchorEnd   = at === "end"   || at === "whole";

  const fetchText = (url: string): Promise<string> => fetch(url).then((response) => {
    if (!response.ok) {
      throw new Error(`HTTP ${response.status}`);
    }
    return response.text();
  });

  // The word data is optional: without it, results are still found, just not filtered, ranked,
  // or capitalized.
  setStatus("Loading the pronunciation dictionary…");
  Promise.all([fetchText(DICT_URL), fetchText(WORDS_URL).catch(() => "")])
    .then(([dictText, wordsText]) => {
      dict     = parseDictionary(dictText);
      wordInfo = parseWordInfo(wordsText);
      commonness.disabled = wordInfo.size === 0;
      hideOffensive.disabled = wordInfo.size === 0;
      setStatus("");
      if (input.value.trim()) {
        lookUp(initial);
      }
    })
    .catch((error) => {
      setStatus(`Couldn't load the pronunciation dictionary (${error.message}). Try reloading the page.`, true);
    });
}

if (typeof document !== "undefined") {
  // Module scripts are deferred, but guard in case the DOM is still loading.
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initPage);
  } else {
    initPage();
  }
}
