// ╭───────────────────────────────────────────────────────────────╮
// │        Pun finder: words that share sounds with a word        │
// ╰───────────────────────────────────────────────────────────────╯
// Looks up a word in the CMU Pronouncing Dictionary (CMUdict), shows each of its pronunciations
// as a row of phonemes, and lets the user select some of them. Every other dictionary word whose
// pronunciation contains the selected phonemes (in order) is listed as a pun candidate.
//
// Below each phoneme are similar-sounding alternatives (see "Similar sounds"). At each position,
// the user can select the original sound, any of its alternatives, or several; a word matches if
// it has any of the selected sounds at that position.
//
// If the selected positions aren't contiguous, each run of selected positions must appear in
// order, with at least one phoneme between them, standing in for the unselected phonemes.
//
// Stress is ignored unless the user locks it on a stressed vowel, and the match can be anywhere
// in a word unless the user pins the selection to the word's start or end (or both).
//
// CMUdict lines look like "read(2) R IY1 D # comment". Phonemes are ARPAbet symbols; vowels end
// with a stress digit (0 = none, 1 = primary, 2 = secondary).
//
// CMUdict includes many rare words and surnames, so each word's frequency rank and whether it's
// a real word come from assets/data/pun_finder_words.tsv, generated by
// dev/generate_pun_finder_words.py from wordfreq and the Hunspell en_US spelling dictionary. Its
// lines are "word<TAB>zipf<TAB>kind<TAB>offensive", most common first, where word is spelled for
// display (proper nouns capitalized), zipf is log10 of the frequency per billion words, kind is
// "w" (dictionary word), "n" (proper noun), or "" (neither, e.g. a rare surname), and offensive
// is a severity from 1 (mild) to 4 (severe), or empty, from dsojevic/profanity-list.
//
// Matches are grouped by how closely they match (extra sounds, then similar sounds), and sorted
// within each group from most to least common.

