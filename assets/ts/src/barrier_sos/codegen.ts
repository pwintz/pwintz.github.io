// ╭───────────────────────────────────────────────────────────────╮
// │        Formulating the SOS program: LaTeX, SOSTOOLS, YALMIP    │
// ╰───────────────────────────────────────────────────────────────╯
// Each generator writes the same SOS program (see problem.ts): the barrier B_q, flow maps, jump
// maps, and multipliers are defined first, then one SOS constraint per condition. Polynomials
// from the page are written out expanded, with parameters replaced by their values. The MATLAB
// code only sets up the program; solving it is left to SOSTOOLS or YALMIP and an SDP solver.

import { Poly, polyToCode, polyToLatex, monomialExponents } from "./poly";
import { Compiled, Condition, Multiplier, barrierDegree } from "./problem";

export type Target = "latex" | "sostools" | "yalmip";

const PAGE_URL = "https://paulwintz.com/tools/barrier_sos/";

interface Ctx {
  cp: Compiled;
  code: (p: Poly) => string;
  varList: (vars: number[]) => string;
}

// The terms in an SOS condition other than the multiplier terms, e.g. "-dB_1 + lam_1*B_1".
function mainTerms(c: Condition, cp: Compiled, mul: string): string {
  const q = c.mode + 1;
  switch (c.kind) {
    case "init": return `-B_${q}`;
    case "unsafe": return `B_${q} - epsB`;
    case "flow": {
      const mode = cp.modes[c.mode];
      let s = `-dB_${q}`;
      if (!(mode.lambda.kind === "fixed" && mode.lambda.poly.isZero())) s += ` + lam_${q}${mul}B_${q}`;
      if (cp.iqc) s += ` - tau${mul}phi`;
      return s;
    }
    case "jump": {
      const jump = cp.jumps[c.jump];
      let s = `-Bplus_${c.jump + 1}`;
      if (!(jump.sigma.kind === "fixed" && jump.sigma.value === 0)) s += ` + sig_${c.jump + 1}${mul}B_${jump.from + 1}`;
      return s;
    }
  }
}

function conditionComment(c: Condition, cp: Compiled): string {
  const q = c.mode + 1;
  const name = cp.modes[c.mode].name.trim();
  const modeText = `mode ${q}${name ? ` (${name})` : ""}`;
  switch (c.kind) {
    case "init": return `Initial set, ${modeText}: B_${q} <= 0 on X0${c.piece}`;
    case "unsafe": return `Unsafe set, ${modeText}: B_${q} >= epsB on Xu${c.piece}`;
    case "flow": return `Flows, ${modeText}: dB_${q}/dt <= lam_${q}*B_${q} on C x W${c.piece}`;
    case "jump": {
      const jump = cp.jumps[c.jump];
      return `Jump ${c.jump + 1}, mode ${jump.from + 1} -> ${jump.to + 1}: B_${jump.to + 1}(g) <= sig_${c.jump + 1}*B_${jump.from + 1} on D x V${c.piece}`;
    }
  }
}

function multiplierTerms(ms: Multiplier[], ctx: Ctx, mul: string): string {
  return ms.map((m) => ` - ${m.name}${mul}(${ctx.code(m.constraint)})`).join("");
}

function header(cp: Compiled, comment: string, lines: string[]): string {
  return [
    `${comment} Barrier certificate ${cp.task === "synthesize" ? "search" : "verification"} for a hybrid system H = (C, F, D, G)`,
    `${comment} using sum-of-squares programming. Generated by ${PAGE_URL}`,
    `${comment}`,
    ...lines.map((l) => `${comment} ${l}`.trimEnd()),
  ].join("\n");
}

function summaryLines(cp: Compiled): string[] {
  const lines = [
    "If the solver finds a solution, then no solution of H that starts in the initial set",
    "reaches the unsafe set. Check that the solver reports success without numerical problems.",
  ];
  if (cp.task === "synthesize") {
    lines.push("If it is infeasible, try a higher degree for B, a different λ or σ, or verify mode.");
  }
  return lines;
}

// ⋘──────── MATLAB: SOSTOOLS ────────⋙

export function generateSostools(cp: Compiled): string {
  const ctx: Ctx = {
    cp,
    code: (p) => polyToCode(p, cp.names, "^"),
    varList: (vars) => `[${vars.map((i) => cp.names[i]).join("; ")}]`,
  };
  const out: string[] = [];
  out.push(header(cp, "%", ["Requires SOSTOOLS (https://github.com/oxfordcontrol/SOSTOOLS) and an SDP solver", "such as SeDuMi or MOSEK.", "", ...summaryLines(cp)]));
  out.push("");
  out.push(`pvar ${cp.names.join(" ")}`);
  out.push(`z = ${ctx.varList(cp.z)};`);
  out.push(`prog = sosprogram(${ctx.varList([...cp.z, ...cp.w, ...cp.v])});`);
  out.push(`epsB = ${cp.epsilon};  % Required margin: B >= epsB on the unsafe set`);
  if (cp.iqc) {
    out.push(`phi = ${ctx.code(cp.iqc)};  % Integral constraint: int phi dt >= 0`);
    out.push("[prog, tau] = sossosvar(prog, monomials(z, 0));  % tau >= 0");
  }

  const dB = (q: number) => cp.z.map((zi, k) => `diff(B_${q}, ${cp.names[zi]})*f_${q}(${k + 1})`).join(" + ");
  cp.modes.forEach((mode, qi) => {
    const q = qi + 1;
    out.push("", `%% Mode ${q}${mode.name.trim() ? `: ${mode.name.trim()}` : ""}`);
    if (mode.B.kind === "unknown") out.push(`[prog, B_${q}] = sospolyvar(prog, monomials(z, 0:${mode.B.degree}));  % Barrier function`);
    else out.push(`B_${q} = ${ctx.code(mode.B.poly)};  % Barrier function`);
    out.push(`f_${q} = [${mode.f.map(ctx.code).join("; ")}];  % Flow map`);
    out.push(`dB_${q} = ${dB(q)};`);
    if (mode.lambda.kind === "free") out.push(`[prog, lam_${q}] = sospolyvar(prog, monomials(z, 0:${mode.lambda.degree}));`);
    else if (!mode.lambda.poly.isZero()) out.push(`lam_${q} = ${ctx.code(mode.lambda.poly)};`);
  });

  cp.jumps.forEach((jump, ji) => {
    const j = ji + 1;
    out.push("", `%% Jump ${j}: mode ${jump.from + 1} -> mode ${jump.to + 1}`);
    out.push(`g_${j} = [${jump.g.map(ctx.code).join("; ")}];  % Jump map`);
    out.push(`Bplus_${j} = subs(B_${jump.to + 1}, z, g_${j});  % B_${jump.to + 1}(g_${j})`);
    if (jump.sigma.kind === "free") {
      out.push(`[prog, sig_${j}] = sossosvar(prog, monomials(${ctx.varList([...cp.z, ...jump.vVars])}, 0:${jump.sigma.degree / 2}));`);
    } else if (jump.sigma.value !== 0) {
      out.push(`sig_${j} = ${jump.sigma.value};`);
    }
  });

  out.push("", "%% SOS conditions");
  for (const c of cp.conditions) {
    out.push(`% ${conditionComment(c, cp)}`);
    const vars = ctx.varList(c.vars);
    for (const m of c.multipliers) {
      if (m.kind === "sos") out.push(`[prog, ${m.name}] = sossosvar(prog, monomials(${vars}, 0:${m.degree / 2}));`);
      else out.push(`[prog, ${m.name}] = sospolyvar(prog, monomials(${vars}, 0:${m.degree}));`);
    }
    out.push(`prog = sosineq(prog, ${mainTerms(c, cp, "*")}${multiplierTerms(c.multipliers, ctx, "*")});`);
    out.push("");
  }

  out.push("%% Solve");
  out.push("opts.solver = 'sedumi';  % Or 'mosek', 'sdpt3', ...");
  out.push("prog = sossolve(prog, opts);");
  out.push("% Check prog.solinfo.info (feasratio near 1, pinf = dinf = 0) before trusting the result.");
  cp.modes.forEach((mode, qi) => {
    if (mode.B.kind === "unknown") out.push(`B_${qi + 1}_sol = cleanpoly(sosgetsol(prog, B_${qi + 1}), 1e-8)`);
    if (mode.lambda.kind === "free") out.push(`lam_${qi + 1}_sol = cleanpoly(sosgetsol(prog, lam_${qi + 1}), 1e-8)`);
  });
  cp.jumps.forEach((jump, ji) => {
    if (jump.sigma.kind === "free") out.push(`sig_${ji + 1}_sol = cleanpoly(sosgetsol(prog, sig_${ji + 1}), 1e-8)`);
  });
  if (cp.iqc) out.push("tau_sol = sosgetsol(prog, tau)");
  return out.join("\n") + "\n";
}

// ⋘──────── MATLAB: YALMIP ────────⋙

export function generateYalmip(cp: Compiled): string {
  const ctx: Ctx = {
    cp,
    code: (p) => polyToCode(p, cp.names, "^"),
    varList: (vars) => `[${vars.map((i) => cp.names[i]).join("; ")}]`,
  };
  const out: string[] = [];
  out.push(header(cp, "%", ["Requires YALMIP (https://yalmip.github.io) and an SDP solver such as MOSEK or SeDuMi.", "", ...summaryLines(cp)]));
  out.push("");
  out.push(`sdpvar ${cp.names.join(" ")}`);
  out.push(`z = ${ctx.varList(cp.z)};`);
  out.push("constraints = [];");
  out.push("decvars = [];  % Coefficients of the unknown polynomials");
  out.push(`epsB = ${cp.epsilon};  % Required margin: B >= epsB on the unsafe set`);
  if (cp.iqc) {
    out.push(`phi = ${ctx.code(cp.iqc)};  % Integral constraint: int phi dt >= 0`);
    out.push("tau = sdpvar(1); constraints = [constraints, tau >= 0]; decvars = [decvars; tau];");
  }

  // Monomials of B_q, written out so that they can also be evaluated at a jump map.
  const monos = (q: number) => monomialExponents(cp.names.length, cp.z, (cp.modes[q].B as { degree: number }).degree);
  const monoCode = (exps: number[], sub: (k: number) => string) => {
    const factors = cp.z.flatMap((zi, k) => exps[zi] === 0 ? [] : [exps[zi] === 1 ? sub(k) : `${sub(k)}^${exps[zi]}`]);
    return factors.length ? factors.join("*") : "1";
  };

  cp.modes.forEach((mode, qi) => {
    const q = qi + 1;
    out.push("", `%% Mode ${q}${mode.name.trim() ? `: ${mode.name.trim()}` : ""}`);
    if (mode.B.kind === "unknown") {
      out.push(`mB_${q} = [${monos(qi).map((e) => monoCode(e, (k) => cp.names[cp.z[k]])).join("; ")}];`);
      out.push(`cB_${q} = sdpvar(length(mB_${q}), 1); decvars = [decvars; cB_${q}];`);
      out.push(`B_${q} = cB_${q}' * mB_${q};  % Barrier function`);
    } else {
      out.push(`B_${q} = ${ctx.code(mode.B.poly)};  % Barrier function`);
    }
    out.push(`f_${q} = [${mode.f.map(ctx.code).join("; ")}];  % Flow map`);
    out.push(`dB_${q} = jacobian(B_${q}, z) * f_${q};`);
    if (mode.lambda.kind === "free") {
      out.push(`[lam_${q}, clam_${q}] = polynomial(z, ${mode.lambda.degree}); decvars = [decvars; clam_${q}];`);
    } else if (!mode.lambda.poly.isZero()) {
      out.push(`lam_${q} = ${ctx.code(mode.lambda.poly)};`);
    }
  });

  cp.jumps.forEach((jump, ji) => {
    const j = ji + 1;
    const to = cp.modes[jump.to];
    out.push("", `%% Jump ${j}: mode ${jump.from + 1} -> mode ${jump.to + 1}`);
    out.push(`g_${j} = [${jump.g.map(ctx.code).join("; ")}];  % Jump map`);
    if (to.B.kind === "unknown") {
      out.push(`Bplus_${j} = cB_${jump.to + 1}' * [${monos(jump.to).map((e) => monoCode(e, (k) => `g_${j}(${k + 1})`)).join("; ")}];  % B_${jump.to + 1}(g_${j})`);
    } else {
      out.push(`Bplus_${j} = ${ctx.code(to.B.poly.compose(jump.g))};  % B_${jump.to + 1}(g_${j})`);
    }
    if (jump.sigma.kind === "free") {
      out.push(`[sig_${j}, csig_${j}] = polynomial(${ctx.varList([...cp.z, ...jump.vVars])}, ${jump.sigma.degree});`);
      out.push(`constraints = [constraints, sos(sig_${j})]; decvars = [decvars; csig_${j}];`);
    } else if (jump.sigma.value !== 0) {
      out.push(`sig_${j} = ${jump.sigma.value};`);
    }
  });

  out.push("", "%% SOS conditions");
  for (const c of cp.conditions) {
    out.push(`% ${conditionComment(c, cp)}`);
    const vars = ctx.varList(c.vars);
    for (const m of c.multipliers) {
      out.push(`[${m.name}, c_${m.name}] = polynomial(${vars}, ${m.degree}); decvars = [decvars; c_${m.name}];`);
      if (m.kind === "sos") out.push(`constraints = [constraints, sos(${m.name})];`);
    }
    out.push(`constraints = [constraints, sos(${mainTerms(c, cp, "*")}${multiplierTerms(c.multipliers, ctx, "*")})];`);
    out.push("");
  }

  out.push("%% Solve");
  out.push("ops = sdpsettings('solver', 'mosek');  % Or 'sedumi', 'sdpt3', ...");
  out.push("sol = solvesos(constraints, [], ops, decvars);");
  out.push("disp(sol.info)");
  out.push("if sol.problem == 0");
  cp.modes.forEach((mode, qi) => {
    if (mode.B.kind === "unknown") out.push(`    sdisplay(clean(value(cB_${qi + 1})' * mB_${qi + 1}, 1e-8))  % B_${qi + 1}`);
    if (mode.lambda.kind === "free") out.push(`    sdisplay(clean(replace(lam_${qi + 1}, clam_${qi + 1}, value(clam_${qi + 1})), 1e-8))  % lam_${qi + 1}`);
  });
  if (cp.iqc) out.push("    disp(value(tau))  % tau");
  out.push("end");
  return out.join("\n") + "\n";
}

// ⋘──────── LaTeX ────────⋙
// The SOS program as structured LaTeX, used both to render it on the page and to produce LaTeX
// source that can be pasted into a paper.

export interface LatexDef { math: string; note: string; }        // e.g. "B_1 \in R_4[x_1, x_2]", "unknown"
export interface LatexCondition {
  title: string;         // Plain text, e.g. "Flows, mode 1"
  property: string;      // Math: what the condition ensures, e.g. "\langle \nabla B_1, f_1 \rangle \le 0 on C_1 \times W_1"
  sos: string;           // Math: the SOS constraint
  multipliers: string;   // Math: declarations of the multipliers, or ""
}
export interface LatexProgram {
  defs: { heading: string; items: LatexDef[] }[];
  conditions: LatexCondition[];
}

export function buildLatex(cp: Compiled): LatexProgram {
  const tex = (p: Poly) => polyToLatex(p, cp.latexNames);
  const vars = (idx: number[]) => idx.map((i) => cp.latexNames[i]).join(", ");
  const column = (ps: Poly[]) => `\\begin{bmatrix} ${ps.map(tex).join(" \\\\ ")} \\end{bmatrix}`;
  const defs: LatexProgram["defs"] = [];

  cp.modes.forEach((mode, qi) => {
    const q = qi + 1;
    const items: LatexDef[] = [];
    if (mode.B.kind === "unknown") {
      const count = monomialExponents(cp.names.length, cp.z, mode.B.degree).length;
      items.push({ math: `B_{${q}} \\in \\mathbb{R}_{${mode.B.degree}}[${vars(cp.z)}]`, note: `unknown, ${count} coefficients` });
    } else {
      items.push({ math: `B_{${q}} = ${tex(mode.B.poly)}`, note: "" });
    }
    items.push({ math: `f_{${q}} = ${column(mode.f)}`, note: "" });
    if (mode.lambda.kind === "free") {
      items.push({ math: `\\lambda_{${q}} \\in \\mathbb{R}_{${mode.lambda.degree}}[${vars(cp.z)}]`, note: "unknown" });
    } else if (!mode.lambda.poly.isZero()) {
      items.push({ math: `\\lambda_{${q}} = ${tex(mode.lambda.poly)}`, note: "fixed" });
    }
    const name = mode.name.trim();
    defs.push({ heading: `Mode ${q}${name ? ` (${name})` : ""}`, items });
  });

  cp.jumps.forEach((jump, ji) => {
    const j = ji + 1;
    const items: LatexDef[] = [{ math: `g_{${j}} = ${column(jump.g)}`, note: "" }];
    if (jump.sigma.kind === "free") {
      items.push({ math: `\\sigma_{${j}} \\in \\Sigma_{${jump.sigma.degree}}[${vars([...cp.z, ...jump.vVars])}]`, note: "unknown" });
    } else if (jump.sigma.value !== 0) {
      items.push({ math: `\\sigma_{${j}} = ${jump.sigma.value}`, note: "fixed" });
    }
    defs.push({ heading: `Jump ${j}: mode ${jump.from + 1} → mode ${jump.to + 1}`, items });
  });

  if (cp.iqc) {
    defs.push({ heading: "Integral constraint", items: [
      { math: `\\phi = ${tex(cp.iqc)}`, note: "" },
      { math: `\\tau \\ge 0`, note: "unknown" },
    ] });
  }

  const conditions = cp.conditions.map((c): LatexCondition => {
    const q = c.mode + 1;
    let main: string, property: string, title: string;
    switch (c.kind) {
      case "init":
        title = `Initial set, mode ${q}${c.piece}`;
        main = `-B_{${q}}`;
        property = `B_{${q}} \\le 0 \\text{ on } X_{0,${q}}`;
        break;
      case "unsafe":
        title = `Unsafe set, mode ${q}${c.piece}`;
        main = `B_{${q}} - ${cp.epsilon}`;
        property = `B_{${q}} \\ge \\varepsilon = ${cp.epsilon} \\text{ on } X_{u,${q}}`;
        break;
      case "flow": {
        const lambdaZero = cp.modes[c.mode].lambda.kind === "fixed" && (cp.modes[c.mode].lambda as { poly: Poly }).poly.isZero();
        title = `Flows, mode ${q}${c.piece}`;
        main = `-\\langle \\nabla B_{${q}}, f_{${q}} \\rangle`;
        if (!lambdaZero) main += ` + \\lambda_{${q}} B_{${q}}`;
        if (cp.iqc) main += ` - \\tau\\,\\phi`;
        property = `\\langle \\nabla B_{${q}}, f_{${q}} \\rangle ${cp.iqc ? "+ \\tau\\phi " : ""}\\le ${lambdaZero ? "0" : `\\lambda_{${q}} B_{${q}}`} \\text{ on } C_{${q}} \\times W_{${q}}`;
        break;
      }
      case "jump": {
        const jump = cp.jumps[c.jump];
        const [j, p, r] = [c.jump + 1, jump.from + 1, jump.to + 1];
        const sigmaZero = jump.sigma.kind === "fixed" && jump.sigma.value === 0;
        title = `Jump ${j}, mode ${p} → mode ${r}${c.piece}`;
        main = `-B_{${r}} \\circ g_{${j}}`;
        if (!sigmaZero) main += ` + \\sigma_{${j}} B_{${p}}`;
        property = `B_{${r}} \\circ g_{${j}} \\le ${sigmaZero ? "0" : `\\sigma_{${j}} B_{${p}}`} \\text{ on } D_{${j}} \\times V_{${j}}`;
        break;
      }
    }
    const mults = c.multipliers.map((m) => ` - ${multLatex(m.name)} \\big(${tex(m.constraint)}\\big)`).join("");
    const multipliers = c.multipliers.map((m) =>
      `${multLatex(m.name)} \\in ${m.kind === "sos" ? "\\Sigma" : "\\mathbb{R}"}_{${m.degree}}[${vars(c.vars)}]`).join(",\\ ");
    return { title, property, sos: `${main}${mults} \\in \\Sigma_{${c.degree}}[${vars(c.vars)}]`, multipliers };
  });

  return { defs, conditions };
}

// LaTeX source for the whole program.
export function generateLatexSource(cp: Compiled): string {
  const prog = buildLatex(cp);
  const out: string[] = [
    `% SOS program for a barrier certificate of a hybrid system H = (C, F, D, G).`,
    `% Generated by ${PAGE_URL}`,
    `% \\Sigma_d[x] denotes SOS polynomials of degree at most d, and \\mathbb{R}_d[x] all polynomials of degree at most d.`,
    "",
  ];
  for (const d of prog.defs) {
    out.push(`% ${d.heading}`);
    out.push("\\begin{align*}");
    out.push(d.items.map((it) => `  ${it.math}${it.note ? ` && \\text{(${it.note})}` : ""}`).join(" \\\\\n"));
    out.push("\\end{align*}");
  }
  out.push(cp.task === "synthesize" ? "Find the unknowns above such that" : "Find multipliers such that");
  out.push("\\begin{align*}");
  out.push(prog.conditions.map((c) => `  & ${c.sos} && \\text{(${c.title})}`).join(" \\\\\n"));
  out.push("\\end{align*}");
  const mults = prog.conditions.filter((c) => c.multipliers).map((c) => c.multipliers);
  if (mults.length > 0) {
    out.push("where");
    out.push("\\begin{align*}");
    out.push(mults.map((m) => `  & ${m}`).join(" \\\\\n"));
    out.push("\\end{align*}");
  }
  return out.join("\n") + "\n";
}

function multLatex(name: string): string {
  const [base, k] = name.split("_");
  return base === "s" ? `s_{${k}}` : `\\mu_{${k}}`;
}

// ⋘──────── Problem size ────────⋙
// Sizes of the SOS program and of the SDP it becomes in the standard Gram-matrix form: each SOS
// polynomial p of degree 2d in k variables is p = m(x)' Q m(x) with Q ⪰ 0, where m(x) holds all
// C(k + d, d) monomials of degree at most d, and matching coefficients gives one linear equation per
// monomial of degree at most 2d. Unknown SOS multipliers are represented by their Gram matrices.
// Toolboxes may shrink m(x) (e.g., with Newton polytopes), so these are upper bounds.

export interface UnknownGroup { label: string; latex: string; count: number; coefficients: number; }

export interface ProblemSize {
  indeterminates: number;           // Variables z, w, v that appear
  unknowns: UnknownGroup[];         // Unknown polynomials, grouped by role
  coefficients: number;             // Total unknown coefficients
  sosConstraints: number;           // SOS constraints from the barrier conditions
  sosMultipliers: number;           // Unknown polynomials that are required to be SOS
  sdp: {
    blocks: { size: number; count: number }[];  // PSD blocks, largest first
    freeScalars: number;            // Coefficients of free (non-SOS) unknown polynomials
    gramScalars: number;            // Entries of the symmetric Gram matrices
    equalities: number;             // Coefficient-matching equations
  };
}

function binomial(n: number, k: number): number {
  let r = 1;
  for (let i = 1; i <= k; i++) r = (r * (n - k + i)) / i;
  return Math.round(r);
}

export function problemSize(cp: Compiled): ProblemSize {
  const nMonos = (k: number, deg: number) => binomial(k + deg, deg);
  const groups = new Map<string, UnknownGroup>();
  const addUnknown = (label: string, latex: string, coefficients: number) => {
    const g = groups.get(label) ?? { label, latex, count: 0, coefficients: 0 };
    g.count += 1;
    g.coefficients += coefficients;
    groups.set(label, g);
  };
  const blocks = new Map<number, number>();
  const addBlock = (size: number) => blocks.set(size, (blocks.get(size) ?? 0) + 1);
  let freeScalars = 0, equalities = 0, sosMultipliers = 0;

  const used = new Set<number>(cp.z);
  cp.modes.forEach((m) => m.wVars.forEach((i) => used.add(i)));
  cp.jumps.forEach((j) => j.vVars.forEach((i) => used.add(i)));

  cp.modes.forEach((m) => {
    if (m.B.kind === "unknown") {
      const c = nMonos(cp.z.length, m.B.degree);
      addUnknown("Barrier functions", "B_q", c);
      freeScalars += c;
    }
    if (m.lambda.kind === "free") {
      const c = nMonos(cp.z.length, m.lambda.degree);
      addUnknown("Flow multipliers", "\\lambda_q", c);
      freeScalars += c;
    }
  });
  cp.jumps.forEach((j) => {
    if (j.sigma.kind === "free") {
      const k = cp.z.length + j.vVars.length;
      addUnknown("Jump multipliers (SOS)", "\\sigma_j", nMonos(k, j.sigma.degree));
      addBlock(nMonos(k, j.sigma.degree / 2));
      sosMultipliers += 1;
    }
  });
  if (cp.iqc) {
    addUnknown("Integral-constraint multiplier", "\\tau", 1);
    addBlock(1);
    sosMultipliers += 1;
  }
  for (const c of cp.conditions) {
    const k = c.vars.length;
    for (const m of c.multipliers) {
      if (m.kind === "sos") {
        addUnknown("S-procedure multipliers (SOS)", "s_i", nMonos(k, m.degree));
        addBlock(nMonos(k, m.degree / 2));
        sosMultipliers += 1;
      } else {
        const coeffs = nMonos(k, m.degree);
        addUnknown("Equality multipliers", "\\mu_k", coeffs);
        freeScalars += coeffs;
      }
    }
    addBlock(nMonos(k, c.degree / 2));
    equalities += nMonos(k, c.degree);
  }

  const unknowns = [...groups.values()];
  const blockList = [...blocks].map(([size, count]) => ({ size, count })).sort((a, b) => b.size - a.size);
  return {
    indeterminates: used.size,
    unknowns,
    coefficients: unknowns.reduce((sum, g) => sum + g.coefficients, 0),
    sosConstraints: cp.conditions.length,
    sosMultipliers,
    sdp: {
      blocks: blockList,
      freeScalars,
      gramScalars: blockList.reduce((sum, b) => sum + b.count * b.size * (b.size + 1) / 2, 0),
      equalities,
    },
  };
}
